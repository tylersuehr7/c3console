#!/usr/bin/env python3
"""Generate the firmware's default calibration curves from config/calibration.json.

The MCU converts raw ADC counts to engineering units with the curves in
firmware/esp32/lib/c3fw/src/c3fw/lookup.hpp until a bench `cal save` replaces a
channel. Those defaults must be the same placeholder table the Pi ships, so the
calibration screen and the frames it receives agree. This script is the only
thing that writes lookup.hpp; tests/test_firmware_filters.cpp fails when the
header and the JSON drift apart.

    python3 tools/generate_calibration.py            # rewrite lookup.hpp
    python3 tools/generate_calibration.py --check    # exit 1 if it would change
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = ROOT / "config" / "calibration.json"
HEADER_PATH = ROOT / "firmware" / "esp32" / "lib" / "c3fw" / "src" / "c3fw" / "lookup.hpp"

# telemetry::Channel order; the header indexes curves by it.
CHANNELS = ("fuel", "oil", "clt", "volt")
FULL_SCALE_COUNTS = 32767  # ADS1115 positive full scale


def float_literal(value: float) -> str:
    text = repr(float(value))
    if "e" in text or "E" in text:
        text = f"{value:.9f}".rstrip("0").rstrip(".")
    if "." not in text:
        text += ".0"
    return text + "F"


def curve_literal(points: list[dict]) -> str:
    knots = ", ".join(f"{{{int(p['raw'])}, {float_literal(p['value'])}}}" for p in points)
    return f"Curve{{{knots}}}"


def render(document: dict) -> str:
    channels = document["channels"]
    missing = [name for name in CHANNELS if name not in channels]
    if missing:
        raise SystemExit(f"calibration.json lacks channels: {', '.join(missing)}")

    literals = []
    for name in CHANNELS:
        points = channels[name]["points"]
        if len(points) != 2:
            # The firmware defaults are literals built from two knots; a measured table with
            # more knots is loaded from NVS, not compiled in.
            raise SystemExit(f"channel {name}: the shipped placeholder must have exactly 2 points, has {len(points)}")
        raws = [int(p["raw"]) for p in points]
        if raws != sorted(set(raws)):
            raise SystemExit(f"channel {name}: raw must be strictly increasing")
        literals.append((curve_literal(points) + ",", name))

    # Trailing comments aligned the way clang-format aligns them, so the output is format-clean.
    width = max(len(literal) for literal, _ in literals)
    curves = [f"      {literal.ljust(width)}  // {name}" for literal, name in literals]

    placeholder = "true" if document.get("placeholder", True) else "false"
    body = "\n".join(curves)
    return f"""// Generated by tools/generate_calibration.py from config/calibration.json. Do not edit by hand;
// tests/test_firmware_filters.cpp fails when this file and the JSON disagree.
//
// These are the conversion curves the MCU boots with. They are PLACEHOLDERS, not bench
// calibration (AGENTS.md invariant 5): identity-shaped lines that make every channel readable
// on the bench. A channel leaves this table only when a validated `cal save` succeeds.
#pragma once

#include "telemetry/frame.hpp"
#include "utils/linear_curve.hpp"

#include <array>
#include <cstddef>
#include <cstdint>

namespace c3fw {{

using CalPoint = c3::utils::CurvePoint;
using Curve = c3::utils::LinearCurve;

constexpr std::size_t kMaxCalPoints = Curve::kCapacity;
constexpr std::int32_t kFullScaleCounts = {FULL_SCALE_COUNTS};

/// Mirrors the JSON's "placeholder" flag so a build cannot claim calibration it does not have.
constexpr bool kPlaceholderCalibration = {placeholder};

/// The shipped defaults, indexed by c3::telemetry::Channel.
[[nodiscard]] constexpr std::array<Curve, c3::telemetry::kChannelCount> placeholder_curves() noexcept {{
  return {{
{body}
  }};
}}

}}  // namespace c3fw
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 instead of writing when the header is stale")
    args = parser.parse_args()

    with JSON_PATH.open(encoding="utf-8") as handle:
        document = json.load(handle)
    text = render(document)

    current = HEADER_PATH.read_text(encoding="utf-8") if HEADER_PATH.exists() else None
    if args.check:
        if current != text:
            print(f"{HEADER_PATH.relative_to(ROOT)} is stale; run tools/generate_calibration.py", file=sys.stderr)
            return 1
        return 0

    if current != text:
        HEADER_PATH.write_text(text, encoding="utf-8")
        print(f"wrote {HEADER_PATH.relative_to(ROOT)}")
    else:
        print(f"{HEADER_PATH.relative_to(ROOT)} already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
